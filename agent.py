"""Mocked LangGraph SRE-agent take-home prototype.

Incident data, read tools, assessment, action execution and post-action
verification are deterministic local mocks. No real external API is called.
"""
from __future__ import annotations
import json
import os
import sqlite3
import time
from pathlib import Path
from typing import Any, Literal, TypedDict
from langgraph.checkpoint.memory import MemorySaver
from langgraph.graph import END, START, StateGraph
from pydantic import BaseModel, ConfigDict, Field, ValidationError

DB_PATH = Path(os.getenv("AGENT_DB_PATH", "runtime/agent.db"))
MAX_TOOL_CALLS = 5
ALLOWED_ROLLBACK_VERSIONS = {"checkout-v2.8.1"}


class Incident(BaseModel):
    model_config = ConfigDict(extra="forbid")
    incident_id: str
    tenant_id: str
    service: str
    severity: Literal["SEV-1", "SEV-2", "SEV-3", "SEV-4"]
    summary: str


class Evidence(BaseModel):
    model_config = ConfigDict(extra="forbid")
    evidence_id: str
    tenant_id: str
    source: str
    observed_at: str
    freshness_seconds: int = Field(ge=0)
    status: Literal["ok", "partial", "unavailable"]
    data: dict[str, Any]


class ProposedAction(BaseModel):
    model_config = ConfigDict(extra="forbid")
    tool: Literal["rollback_deployment"]
    arguments: dict[str, str]


class ActionAuthorization(BaseModel):
    """Trusted approval grant injected by the caller, never generated by the model."""
    model_config = ConfigDict(extra="forbid")
    tenant_id: str
    incident_id: str
    action: Literal["rollback_deployment"]
    arguments: dict[str, str]
    approved_by: str = Field(min_length=1)


class Assessment(BaseModel):
    model_config = ConfigDict(extra="forbid")
    summary: str
    hypotheses: list[str]
    supporting_evidence_ids: list[str]
    contradicting_evidence_ids: list[str] = []
    missing_information: list[str] = []
    recommendation: str
    action: ProposedAction | None = None
    confidence: float = Field(ge=0.0, le=1.0)


class AgentState(TypedDict, total=False):
    incident: dict[str, Any]
    tenant_id: str
    evidence: list[dict[str, Any]]
    tool_errors: list[str]
    tool_calls: int
    assessment: dict[str, Any]
    authorization: dict[str, Any] | None
    authorization_status: str
    action_result: dict[str, Any]
    verification: dict[str, Any]
    mock_recovery: bool
    next_recommendation: str
    status: str
    error: str


class IncidentStore:
    """SQLite WAL snapshot + append-only event journal for the demo."""
    def __init__(self, path: Path = DB_PATH):
        self.path = path
        path.parent.mkdir(parents=True, exist_ok=True)
        with self.connect() as db:
            db.executescript("""
                PRAGMA journal_mode=WAL;
                CREATE TABLE IF NOT EXISTS incidents(
                    tenant_id TEXT NOT NULL, incident_id TEXT NOT NULL,
                    status TEXT NOT NULL, state_json TEXT NOT NULL,
                    updated_at REAL NOT NULL,
                    PRIMARY KEY(tenant_id, incident_id)
                );
                CREATE TABLE IF NOT EXISTS incident_events(
                    seq INTEGER PRIMARY KEY AUTOINCREMENT,
                    tenant_id TEXT NOT NULL, incident_id TEXT NOT NULL,
                    event_type TEXT NOT NULL, payload_json TEXT NOT NULL,
                    created_at REAL NOT NULL
                );
            """)

    def connect(self):
        db = sqlite3.connect(self.path, timeout=10)
        db.row_factory = sqlite3.Row
        return db

    def persist(self, state: AgentState, event_type: str) -> None:
        incident = state["incident"]
        tenant = state["tenant_id"]
        incident_id = incident["incident_id"]
        payload = json.dumps(state, sort_keys=True, default=str)
        with self.connect() as db:
            db.execute("""INSERT INTO incidents VALUES(?,?,?,?,?)
                ON CONFLICT(tenant_id, incident_id) DO UPDATE SET
                status=excluded.status, state_json=excluded.state_json,
                updated_at=excluded.updated_at""",
                (tenant, incident_id, state.get("status", "UNKNOWN"), payload, time.time()))
            db.execute("""INSERT INTO incident_events
                (tenant_id, incident_id, event_type, payload_json, created_at)
                VALUES(?,?,?,?,?)""",
                (tenant, incident_id, event_type, payload, time.time()))


