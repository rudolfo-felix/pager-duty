def assess_incident(incident: Incident, evidence: list[Evidence]) -> Assessment:
    """Fully local deterministic model substitute; no provider call is made."""
    return _mock_assessment(incident, evidence)


def mock_rollback_deployment(
    incident: Incident,
    action: ProposedAction,
    authorization: ActionAuthorization,
) -> dict[str, Any]:
    """Simulate a deployment rollback; this function never calls a real system."""
    if authorization.tenant_id != incident.tenant_id:
        raise PermissionError("authorization tenant does not match incident")
    if authorization.incident_id != incident.incident_id:
        raise PermissionError("authorization incident does not match")
    if authorization.action != action.tool or authorization.arguments != action.arguments:
        raise PermissionError("authorization does not match the proposed action")
    if action.tool != "rollback_deployment":
        raise PermissionError("action is not allowlisted")
    version = action.arguments.get("version")
    if version not in ALLOWED_ROLLBACK_VERSIONS:
        raise PermissionError("deployment version is not allowlisted for this mock")
    if not authorization.approved_by.strip():
        raise PermissionError("authorization must identify the approver")
    return {
        "execution_id": f"mock-exec-{incident.incident_id}-{version}",
        "idempotency_key": f"{incident.tenant_id}:{incident.incident_id}:{action.tool}:{version}",
        "tool": action.tool,
        "arguments": action.arguments,
        "status": "simulated_execution_succeeded",
        "simulated": True,
        "approved_by": authorization.approved_by,
    }


def mock_verify_recovery(incident: Incident, *, recovered: bool) -> Evidence:
    """Return synthetic post-action metrics, independent from pre-action evidence."""
    metrics = (
        {"checkout_success_rate": 0.982, "http_5xx_rate": 0.011, "p95_latency_ms": 510}
        if recovered else
        {"checkout_success_rate": 0.612, "http_5xx_rate": 0.146, "p95_latency_ms": 3200}
    )
    return Evidence(
        evidence_id=f"ev-{incident.incident_id}-post-action-verification",
        tenant_id=incident.tenant_id,
        source="mock.post_action_metrics",
        observed_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        freshness_seconds=5,
        status="ok",
        data=metrics,
    )


def recovery_thresholds_met(evidence: Evidence) -> bool:
    metrics = evidence.data
    return (
        metrics.get("checkout_success_rate", 0) >= 0.95
        and metrics.get("http_5xx_rate", 1) <= 0.02
        and metrics.get("p95_latency_ms", float("inf")) <= 1000
    )


def build_graph(store: IncidentStore | None = None, checkpointer=None):
    store = store or IncidentStore()

    def validate_incident(state: AgentState) -> AgentState:
        incident = Incident.model_validate(state["incident"])
        tenant_id = state["tenant_id"]
        if tenant_id != incident.tenant_id:
            raise PermissionError("tenant boundary violation")
        return {
            "incident": incident.model_dump(), "tenant_id": tenant_id,
            "evidence": [], "tool_errors": [], "tool_calls": 0, "status": "VALIDATED",
        }

    def gather_context(state: AgentState) -> AgentState:
        incident = Incident.model_validate(state["incident"])
        tenant = state["tenant_id"]
        tools = (
            get_service_profile, get_checkout_metrics, get_dependency_health,
            get_recent_deployments, search_incident_history,
        )
        results: list[dict[str, Any]] = []
        errors: list[str] = []
        for tool in tools:
            if len(results) + len(errors) >= MAX_TOOL_CALLS:
                break
            try:
                results.append(tool(tenant, incident).model_dump())
            except Exception as exc:
                errors.append(f"{tool.__name__}: {type(exc).__name__}: {exc}")
        return {
            "evidence": results, "tool_errors": errors,
            "tool_calls": len(results) + len(errors), "status": "CONTEXT_GATHERED",
        }

    def reason(state: AgentState) -> AgentState:
        incident = Incident.model_validate(state["incident"])
        evidence = [Evidence.model_validate(x) for x in state["evidence"]]
        assessment = assess_incident(incident, evidence)
        valid_ids = {x.evidence_id for x in evidence}
        if not set(assessment.supporting_evidence_ids + assessment.contradicting_evidence_ids) <= valid_ids:
            raise ValueError("assessment referenced evidence outside the retrieved context")
        return {"assessment": assessment.model_dump(), "status": "ASSESSED"}

    def check_authorization(state: AgentState) -> AgentState:
        raw_grant = state.get("authorization")
        if not raw_grant:
            return {"authorization_status": "missing", "status": "AWAITING_HUMAN_DECISION"}
        try:
            incident = Incident.model_validate(state["incident"])
            action = ProposedAction.model_validate(state["assessment"]["action"])
            grant = ActionAuthorization.model_validate(raw_grant)
            if grant.tenant_id != incident.tenant_id or grant.incident_id != incident.incident_id:
                raise PermissionError("authorization grant is for a different tenant or incident")
            if grant.action != action.tool or grant.arguments != action.arguments:
                raise PermissionError("authorization grant does not match the proposed action")
            if action.arguments.get("version") not in ALLOWED_ROLLBACK_VERSIONS:
                raise PermissionError("proposed deployment version is not allowlisted")
            if not grant.approved_by.strip():
                raise PermissionError("authorization grant has no approver identity")
            return {"authorization_status": "approved", "status": "AUTHORIZED"}
        except (ValidationError, PermissionError, TypeError, KeyError, ValueError) as exc:
            return {"authorization_status": "rejected", "error": str(exc), "status": "AUTHORIZATION_REJECTED"}

    def execute_action(state: AgentState) -> AgentState:
        incident = Incident.model_validate(state["incident"])
        action = ProposedAction.model_validate(state["assessment"]["action"])
        grant = ActionAuthorization.model_validate(state["authorization"])
        result = mock_rollback_deployment(incident, action, grant)
        return {"action_result": result, "status": "MOCK_ACTION_EXECUTED"}

    def verify_recovery(state: AgentState) -> AgentState:
        incident = Incident.model_validate(state["incident"])
        verification_evidence = mock_verify_recovery(
            incident, recovered=bool(state.get("mock_recovery", True))
        )
        recovered = recovery_thresholds_met(verification_evidence)
        evidence = list(state.get("evidence", []))
        evidence.append(verification_evidence.model_dump())
        return {
            "evidence": evidence,
            "verification": {
                "verified": recovered,
                "evidence_id": verification_evidence.evidence_id,
                "metrics": verification_evidence.data,
            },
            "status": "RECOVERY_VERIFIED" if recovered else "RECOVERY_NOT_CONFIRMED",
        }

    def reassess_after_failed_recovery(state: AgentState) -> AgentState:
        return {
            "next_recommendation": (
                "Recovery was not demonstrated by fresh metrics. Keep the incident open, "
                "do not repeat the write automatically, gather updated dependency/deployment "
                "evidence and request a new human decision before another action."
            ),
            "status": "RECOVERY_NOT_CONFIRMED",
        }

    def persist(state: AgentState) -> AgentState:
        store.persist(state, state.get("status", "UNKNOWN"))
        return {}

    graph = StateGraph(AgentState)
    for name, node in (
        ("validate_incident", validate_incident),
        ("gather_context", gather_context),
        ("reason", reason),
        ("check_authorization", check_authorization),
        ("execute_action", execute_action),
        ("verify_recovery", verify_recovery),
        ("reassess_after_failed_recovery", reassess_after_failed_recovery),
        ("persist", persist),
    ):
        graph.add_node(name, node)

    graph.add_edge(START, "validate_incident")
    graph.add_edge("validate_incident", "gather_context")
    graph.add_edge("gather_context", "reason")
    graph.add_edge("reason", "check_authorization")
    graph.add_conditional_edges(
        "check_authorization",
        lambda state: "execute" if state.get("authorization_status") == "approved" else "stop",
        {"execute": "execute_action", "stop": "persist"},
    )
    graph.add_edge("execute_action", "verify_recovery")
    graph.add_conditional_edges(
        "verify_recovery",
        lambda state: "verified" if state.get("verification", {}).get("verified") else "reassess",
        {"verified": "persist", "reassess": "reassess_after_failed_recovery"},
    )
    graph.add_edge("reassess_after_failed_recovery", "persist")
    graph.add_edge("persist", END)
    return graph.compile(checkpointer=checkpointer or MemorySaver())


def run_investigation(
    incident: Incident,
    *,
    store: IncidentStore | None = None,
    thread_id: str | None = None,
    authorization: ActionAuthorization | None = None,
    mock_recovery: bool = True,
) -> AgentState:
    store = store or IncidentStore()
    graph = build_graph(store=store)
    config = {"configurable": {"thread_id": thread_id or f"{incident.tenant_id}:{incident.incident_id}"}}
    initial: AgentState = {
        "incident": incident.model_dump(),
        "tenant_id": incident.tenant_id,
        "status": "RECEIVED",
        "mock_recovery": mock_recovery,
    }
    if authorization is not None:
        initial["authorization"] = authorization.model_dump()
    return graph.invoke(initial, config=config)


